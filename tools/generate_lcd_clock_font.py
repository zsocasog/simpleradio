"""Generate the small, numeric-only Noto Sans subsets used by standby clocks.

The existing UI fonts stay byte-for-byte unchanged. These subsets live in flash;
neither large glyphs nor a full-screen sprite are allocated in internal RAM.
"""

from PIL import ImageFont

from generate_lcd_font import ROOT, FONT_BOLD, emit_array, glyph_for

OUT = ROOT / "src" / "display" / "lcd_clock_font_data.h"
CHARS = "-0123456789:?"
FONTS = (("Time", 144), ("TimeCompact", 96), ("Day", 112), ("DayCompact", 80))


def main():
    if not FONT_BOLD.exists():
        raise SystemExit(f"Noto Sans Bold not found: {FONT_BOLD}")
    body = [
        "#pragma once",
        '// Generated by tools/generate_lcd_clock_font.py; do not edit glyph data.',
        '// Noto Sans: Copyright The Noto Project Authors, SIL Open Font License 1.1.',
        '#include "lcd_font_data.h"',
        "",
    ]
    total = 0
    for suffix, size in FONTS:
        font = ImageFont.truetype(str(FONT_BOLD), size)
        ascent, descent = font.getmetrics()
        bitmap, glyphs = [], []
        for char in CHARS:
            glyph = glyph_for(font, char)
            glyph["offset"] = len(bitmap)
            bitmap.extend(glyph["data"])
            glyphs.append(glyph)
        prefix = f"kClockFont{suffix}"
        body.extend([emit_array(prefix + "Bitmap", bitmap), "",
                     f"static const LcdGlyph {prefix}Glyphs[] PROGMEM = {{"])
        for glyph in glyphs:
            body.append("  {" + ", ".join(str(glyph[key]) for key in
                ("code", "offset", "width", "height", "x_offset", "y_offset", "x_advance")) + "},")
        body.extend(["};", "", f"static const LcdFont {prefix} PROGMEM = {{"
                     f"{prefix}Glyphs, {prefix}Bitmap, {len(glyphs)}, {ascent + descent}, {ascent}}};", ""])
        total += len(bitmap)
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}: {total} bitmap bytes in flash")


if __name__ == "__main__":
    main()
